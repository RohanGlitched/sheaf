// Copies the EVM deployment records the site reads into web/lib/deployments, and
// writes an index module so the app imports whatever chains are deployed.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
const root = new URL("../", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const src = join(root, "evm", "deployments");
const dst = join(root, "web", "lib", "deployments");
mkdirSync(dst, { recursive: true });
const names = readdirSync(src).filter((f) => f.endsWith(".json") && !/local|hardhat/i.test(f));
for (const f of names) writeFileSync(join(dst, f), readFileSync(join(src, f)));
const idents = names.map((f) => f.replace(/\.json$/, ""));
writeFileSync(
  join(dst, "index.ts"),
  `// Generated by scripts/sync-deployments.mjs. Do not edit.\n` +
    idents.map((n) => `import ${n} from "./${n}.json";`).join("\n") +
    `\n\nexport const DEPLOYMENTS = [${idents.join(", ")}] as const;\n`,
);
console.log({ synced: idents });
